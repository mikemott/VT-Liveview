#!/usr/bin/env node
/**
 * Regenerate src/data/vtTowns.ts from VCGI's Town Boundaries service.
 *
 *   node scripts/build-vt-towns.mjs
 *
 * Needs network access to maps.vcgi.vermont.gov. Town boundaries change very
 * rarely (mergers like Essex/Essex Junction), so this is run by hand.
 */
import { writeFileSync } from 'node:fs';

const SERVICE =
  'https://maps.vcgi.vermont.gov/arcgis/rest/services/VCGI_services/ESRICMP_BuildingFootprintsVT_v1/MapServer/0';
const COUNTY_BY_FIPS = {
  1: 'Addison',
  3: 'Bennington',
  5: 'Caledonia',
  7: 'Chittenden',
  9: 'Essex',
  11: 'Franklin',
  13: 'Grand Isle',
  15: 'Lamoille',
  17: 'Orange',
  19: 'Orleans',
  21: 'Rutland',
  23: 'Washington',
  25: 'Windham',
  27: 'Windsor',
};

const params = new URLSearchParams({
  where: '1=1',
  outFields: 'TOWNNAMEMC,CNTY',
  returnGeometry: 'true',
  outSR: '4326',
  maxAllowableOffset: '0.0005',
  f: 'json',
});
const res = await fetch(`${SERVICE}/query?${params}`);
if (!res.ok) throw new Error(`VCGI query failed: HTTP ${res.status}`);
const data = await res.json();
if (data.exceededTransferLimit) throw new Error('Result truncated; page the query');

/** Signed-area centroid of a ring. */
function ringCentroid(ring) {
  let a = 0;
  let x = 0;
  let y = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const f = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
    a += f;
    x += (ring[j][0] + ring[i][0]) * f;
    y += (ring[j][1] + ring[i][1]) * f;
  }
  a /= 2;
  return { area: Math.abs(a), x: x / (6 * a), y: y / (6 * a) };
}

function pointInRing([px, py], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** A point inside the ring on its horizontal mid-line (for concave shapes). */
function interiorPoint(ring) {
  const ys = ring.map((p) => p[1]);
  const midY = (Math.min(...ys) + Math.max(...ys)) / 2;
  const xs = [];
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > midY !== yj > midY) xs.push(xi + ((midY - yi) * (xj - xi)) / (yj - yi));
  }
  xs.sort((a, b) => a - b);
  return [(xs[0] + xs[1]) / 2, midY];
}

const counties = [...new Set(Object.values(COUNTY_BY_FIPS))].sort();
const round = (n, d) => Math.round(n * 10 ** d) / 10 ** d;

const rows = data.features
  .map((feature) => {
    const rings = feature.geometry.rings;
    let best = null;
    for (const ring of rings) {
      const c = ringCentroid(ring);
      if (!best || c.area > best.area) best = { ...c, ring };
    }
    let label = [best.x, best.y];
    if (!pointInRing(label, best.ring)) label = interiorPoint(best.ring);

    let [west, south, east, north] = [Infinity, Infinity, -Infinity, -Infinity];
    for (const ring of rings) {
      for (const [x, y] of ring) {
        west = Math.min(west, x);
        south = Math.min(south, y);
        east = Math.max(east, x);
        north = Math.max(north, y);
      }
    }
    const county = COUNTY_BY_FIPS[feature.attributes.CNTY];
    if (!county) throw new Error(`Unknown county code ${feature.attributes.CNTY}`);
    return [
      feature.attributes.TOWNNAMEMC,
      counties.indexOf(county),
      round(label[1], 4),
      round(label[0], 4),
      round(west, 3),
      round(south, 3),
      round(east, 3),
      round(north, 3),
    ];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

const out = `/**
 * Vermont towns, cities and gores (${rows.length}), for search (VTL-53).
 *
 * GENERATED by scripts/build-vt-towns.mjs from VCGI Town Boundaries
 * (${SERVICE}).
 * Do not edit by hand; re-run the script instead.
 *
 * Row: [name, county index, label lat, label lng, west, south, east, north]
 * The label point is the area centroid of the largest part (or an interior
 * point when the centroid falls outside an irregular boundary).
 */

export const VT_COUNTIES = ${JSON.stringify(counties)} as const;

export type TownRow = [
  name: string,
  county: number,
  lat: number,
  lng: number,
  west: number,
  south: number,
  east: number,
  north: number,
];

export const VT_TOWNS: readonly TownRow[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;

writeFileSync(new URL('../src/data/vtTowns.ts', import.meta.url), out);
console.log(`Wrote ${rows.length} towns to src/data/vtTowns.ts`);

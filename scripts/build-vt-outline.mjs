#!/usr/bin/env node
/**
 * Regenerate src/data/vermontOutline.ts: Vermont's state outline, dissolved
 * from VCGI's Town Boundaries (the same service as build-vt-towns.mjs). Town
 * boundaries run out to the state line in Lake Champlain and the Connecticut
 * River, so their union is the legal state outline.
 *
 *   node scripts/build-vt-outline.mjs
 *
 * Needs network access to maps.vcgi.vermont.gov. Run by hand; the state line
 * doesn't move.
 */
import { writeFileSync } from 'node:fs';
import polygonClipping from 'polygon-clipping';

const SERVICE =
  'https://maps.vcgi.vermont.gov/arcgis/rest/services/VCGI_services/ESRICMP_BuildingFootprintsVT_v1/MapServer/0';

// Full detail for the dissolve, so neighboring towns share exact edges
const params = new URLSearchParams({
  where: '1=1',
  outFields: 'TOWNNAMEMC',
  returnGeometry: 'true',
  outSR: '4326',
  geometryPrecision: '6',
  f: 'json',
});
const res = await fetch(`${SERVICE}/query?${params}`);
if (!res.ok) throw new Error(`VCGI query failed: HTTP ${res.status}`);
const data = await res.json();
if (data.exceededTransferLimit) throw new Error('Result truncated; page the query');
console.log(`${data.features.length} towns`);

// Esri rings → one polygon per town (holes are fine: union handles them)
const towns = data.features.map((f) => f.geometry.rings);
const union = polygonClipping.union(...towns);

/** Perpendicular distance from p to segment a–b, in degrees (fine at this scale). */
function segDist(p, a, b) {
  const [x, y] = p;
  const [x1, y1] = a;
  const [x2, y2] = b;
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len2 = dx * dx + dy * dy;
  const t = len2 ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / len2)) : 0;
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
}

/** Douglas–Peucker on an open polyline. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  let maxD = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = segDist(points[i], points[0], points[points.length - 1]);
    if (d > maxD) {
      maxD = d;
      index = i;
    }
  }
  if (maxD <= tolerance) return [points[0], points[points.length - 1]];
  const left = simplify(points.slice(0, index + 1), tolerance);
  return left.slice(0, -1).concat(simplify(points.slice(index), tolerance));
}

// ~30 m: invisible at state zoom, still follows the river and lake line closely
const TOLERANCE = 0.0003;
const round = ([x, y]) => [Math.round(x * 1e5) / 1e5, Math.round(y * 1e5) / 1e5];

// Keep outer rings only, and drop specks (slivers left by the dissolve)
const ringArea = (ring) =>
  Math.abs(
    ring.reduce((a, [x1, y1], i) => {
      const [x2, y2] = ring[(i + 1) % ring.length];
      return a + x1 * y2 - x2 * y1;
    }, 0),
  ) / 2;
const outlines = union
  .map((polygon) => polygon[0])
  .filter((ring) => ringArea(ring) > 1e-4)
  .map((ring) => simplify(ring, TOLERANCE).map(round))
  .filter((ring) => ring.length >= 4)
  .sort((a, b) => ringArea(b) - ringArea(a));

const points = outlines.reduce((n, r) => n + r.length, 0);
console.log(`${union.length} parts → ${outlines.length} kept, ${points} points`);

const out = `/**
 * Vermont's state outline (VTL-69), for the border line and the dimming
 * outside the state.
 *
 * GENERATED by scripts/build-vt-outline.mjs from VCGI Town Boundaries
 * (dissolved, simplified to ~30 m). Do not edit by hand; re-run the script.
 *
 * Each entry is one closed outer ring of [lng, lat] points, largest first.
 */
export const VERMONT_OUTLINE: [number, number][][] = ${JSON.stringify(outlines)};
`;
writeFileSync(new URL('../src/data/vermontOutline.ts', import.meta.url), out);
console.log('wrote src/data/vermontOutline.ts');
